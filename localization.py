_CONTROLLED_FIELD_PATTERN = re.compile(
    r"(\*\*(?:Action|Result|Warning added|Case created|Nickname reset|"
    r"Message blocked|Decision|Outcome|Join protection|CAPTCHA every member|"
    r"Nickname protection|Link protection|Image scanning|Moderator exemption|"
    r"Alt-account detection):\*\*\s*)"
    r"(Enabled|Disabled|Yes|No|None|Kicked|Muted|Unmuted|Approved|Denied|"
    r"Restored|Warning|Ban|Kick|Timeout|Resolved|Dismissed)(?=\s*(?:$|\n))"
)


def localize_delivery(locale: str, title: str, description: str) -> tuple[str, str]:
    if locale == "en" or locale not in DELIVERY_PHRASES:
        return title, description
    replacements = DELIVERY_PHRASES[locale]
    values = CONTROLLED_FIELD_VALUES[locale]
    description = _CONTROLLED_FIELD_PATTERN.sub(
        lambda match: match.group(1) + values[match.group(2)], description
    )
    # Longest-first avoids partial replacements such as "You received a warning"
    # consuming the longer "You received a warning in" phrase.
    for source in sorted(replacements, key=len, reverse=True):
        target = replacements[source]
        title = title.replace(source, target)
        description = description.replace(source, target)
    for source, target in SETTING_FIELD_LABELS[locale].items():
        description = description.replace(f"**{source}:**", f"**{target}:**")
    return title, description
