def normalize_language(value: str) -> str | None:
    return LANGUAGE_ALIASES.get(value.strip().casefold())


def translate(locale: str, key: str, **values: object) -> str:
    catalogue = MESSAGES.get(locale, MESSAGES["en"])
    template = catalogue.get(key, MESSAGES["en"].get(key, key))
    return template.format(**values)


